/// «ملخص العمرة» and «ملخص الحج»: the whole rite on one card, stage by
/// stage, for a pilgrim who has just arrived and wants to know what to do
/// next.
///
/// «عايزك تعمل ملخص للعمرة … من ساعة ما وصل اعمل ايه والاذكار اللي بتتقال
/// على مدار العمرة والواجبات والسنن … وتعمل برضو ملخص للحاج» (the owner,
/// 2026-09-24).
///
/// NOTHING HERE IS WORDED BY THE APP. Every line is cut, verbatim, from the
/// same chapter the step cards read - «الفقه المنهجي على مذهب الإمام
/// الشافعي», «الحج والعمرة» (Shamela 6369) - mostly from its own practical
/// walk-through «كيف تحج؟» (pp. 180-188). A « … » marks words left out
/// between two verbatim pieces; nothing is paraphrased, reordered inside a
/// sentence, or «corrected» (CLAUDE.md §1.2 - a slip in the source stays).
/// `hajj_summary_test.dart` checks every piece against the bundled book, so
/// a line that is not in it fails the build.
///
/// The stage titles are the only words that are ours: they name the stage
/// (a place and a time), they carry no ruling. The page each line comes
/// from is kept in the comment beside it for the next person to check; it
/// is not shown - «مش تذكر ارقام الصفحات» (2026-09-23).
///
/// The one Qur'anic passage in the book's own walk-through (al-Baqarah
/// 198-199, in the dhikr at al-Mash'ar al-Haram) is shown from the app's
/// mushaf text, not from the book, whose copy has a stray mark on its first
/// letter: scripture comes from the mushaf.
library;

enum SummaryKind {
  /// What to do: the book's sentence.
  text,

  /// What to say: shown set apart so it can be read aloud as it is.
  dhikr,

  /// An ayah range, drawn from the app's Qur'an text.
  ayah,
}

class SummaryLine {
  final SummaryKind kind;
  final String text;
  final int surah;
  final int fromAyah;
  final int toAyah;

  const SummaryLine.text(this.text)
    : kind = SummaryKind.text,
      surah = 0,
      fromAyah = 0,
      toAyah = 0;

  const SummaryLine.dhikr(this.text)
    : kind = SummaryKind.dhikr,
      surah = 0,
      fromAyah = 0,
      toAyah = 0;

  const SummaryLine.ayah(this.surah, this.fromAyah, this.toAyah)
    : kind = SummaryKind.ayah,
      text = '';

  /// The verbatim pieces a « … » joins.
  List<String> get pieces => kind == SummaryKind.ayah
      ? const []
      : text.split(' … ').map((s) => s.trim()).toList();
}

class SummaryStage {
  final String title;
  final List<SummaryLine> lines;
  const SummaryStage(this.title, this.lines);
}

