def build(flat, en_node, prefix=""):
    out = collections.OrderedDict()
    for k, v in en_node.items():
        dotted = f"{prefix}{k}"
        if isinstance(v, collections.OrderedDict) or isinstance(v, dict):
            out[k] = build(flat, v, dotted + ".")
        else:
            if dotted not in flat:
                print("MISSING:", dotted); sys.exit(1)
            out[k] = flat[dotted]
    return out

